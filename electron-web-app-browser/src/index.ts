// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code (depending on
// whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;
declare const SETTINGS_WINDOW_WEBPACK_ENTRY: string;
declare const SETTINGS_WINDOW_PRELOAD_WEBPACK_ENTRY: string;

let settings: ISettingsDefinition | null = null;
let dotNetProcess: ChildProcess | null = null; 

// Handle creating/removing shortcuts on Windows when installing/uninstalling.
if (require('electron-squirrel-startup')) {
  app.quit();
}

const menu = new Menu();
const submenu = Menu.buildFromTemplate([
  {
    label: 'Reload',
    accelerator: 'CmdOrCtrl+R',
    click: () => {
      const windows = BrowserWindow.getAllWindows();
      windows.forEach(window => window.webContents.reload());
    }
  },
  {
    label: 'Settings',
    accelerator: 'F12',
    click: () => {
      openSettings();
    }
  },
  {
    label: 'Developer Tools',
    accelerator: 'CmdOrCtrl+Shift+I',
    click: () => {
      const windows = BrowserWindow.getAllWindows();
      windows.forEach(window => window.webContents.openDevTools());
    }
  }
]);
menu.append(new MenuItem({ label: 'File', submenu }));
Menu.setApplicationMenu(menu);

let settingsWindow: BrowserWindow | null = null;
const openSettings = async () => {
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    settingsWindow.show();
    settingsWindow.focus();
    return;
  }
  settingsWindow = new BrowserWindow({
    width: 800,
    height: 520,
    parent: mainWindow || null,
    modal: false,
    frame: false,
    webPreferences: {
      sandbox: false, 
      contextIsolation: true,
      nodeIntegration: false,
      webviewTag: true,
      preload: SETTINGS_WINDOW_PRELOAD_WEBPACK_ENTRY,
    }
  });
  settingsWindow.removeMenu();
  settingsWindow.loadURL(SETTINGS_WINDOW_WEBPACK_ENTRY);
  settingsWindow.once('ready-to-show', () => {
    settingsWindow.show();
  });
  settingsWindow.on('closed', () => { 
    simpleLogger.log('settings closed');
    settingsWindow = null; 
  });
};

const closeSettings = () => {
  if(settingsWindow && settingsWindow.closable) {
    simpleLogger.log('closing settings');
    settingsWindow.hide();  // use hide instead of close - because close is closing the parent window as well for some reason.
  }
}

const readSettings = async () : Promise<ISettingsDefinition | null> => {
  if(settings) {
    simpleLogger.log('Using cached settings');
    return settings;
  }
  else {
    simpleLogger.log('Reading settings from file');
    const candidates = [
      path.join(process.cwd(), 'settings.json')
    ];

    for (const p of candidates) {
      try {
        if (fs.existsSync(p)) {
          let settingsString =  fs.readFileSync(p, 'utf8');
          simpleLogger.logDetail('Settings String: ', settingsString);
          if(settingsString && settingsString.length > 0){
            let parsed = null;
            try { 
              parsed = JSON.parse(settingsString); 
            } catch (e) { 
              parsed = null; 
              simpleLogger.error('Unable to parse settings.');
            }
            if(parsed) {
              settings = {
                AppDisplayName: parsed.AppDisplayName || parsed.appDisplayName || '',
                AppPath: parsed.AppPath || parsed.appPath || '',
                ExecutableName: parsed.ExecutableName || parsed.executableName || '',
                HideConsoleWindow: parsed.HideConsoleWindow || false,
                AppUrl: parsed.AppUrl || parsed.appUrl || '',
                AppIcon: parsed.AppIcon || parsed.appIcon || ''
              } as ISettingsDefinition
              simpleLogger.logDetail('Typed/Mapped settings: ', settings);
              return settings;
            }
          }
        }
      } catch (e) {
        simpleLogger.errorDetail('Unable to read settings file.', e);
      }
    }
    return null;
  }  
}

const startApiService = async (): Promise<boolean> => {
  simpleLogger.log('Starting API Service');
  let isStarted = false;
  await readSettings();
  if(settings) {
    isStarted = await isUp(settings.AppUrl);
    if(isStarted) {
      simpleLogger.log(`Service is already running at ${settings.AppUrl}`);
    }
    else {
      if(settings.AppPath && settings.ExecutableName) {
        
        if(process.platform === 'linux' || process.platform === 'win32') {
          const out = fs.openSync(path.join(__dirname, 'out.log'), 'a');
          const err = fs.openSync(path.join(__dirname, 'out.log'), 'a');
          try {
            const exePath = path.join(settings.AppPath, settings.ExecutableName);
            simpleLogger.log(`Attempting to start API Service at ${exePath} on ${process.platform} platform.`);
            dotNetProcess = spawn(exePath, { 
              cwd: settings.AppPath,
              shell: !settings.HideConsoleWindow,
              detached: true,
              stdio: [ 'ignore', out, err ]
            });
            dotNetProcess.unref();
            simpleLogger.log(`Spawned child proces with PID: ${dotNetProcess.pid}`);
            isStarted = true;
          } catch(error) {
            simpleLogger.errorDetail("Failed to spawn child process", error);
          }    
        }
        else {
          simpleLogger.error(`Platform: ${process.platform} is not supported.`);
        }

      }
    }
    
    return isStarted;
  }
  else {
    simpleLogger.error('Settings were not available.  Cannot start API.');
    return false;
  }
}

let webContentsView: WebContentsView | null = null;
const createWebContentsView = (): void => {
  if(!webContentsView) {
    webContentsView = new WebContentsView();    
  }
}

let mainWindow: BrowserWindow | null = null;
const createWindow = (): void => {
  readSettings().then((value: ISettingsDefinition) => {
    let appTitle = value?.AppDisplayName ?? "Web Application Browser";
    let appTitleLoading = `${appTitle} - Loading...`
    let appIcon = value?.AppIcon ?? "";
    // Create the browser window.
    mainWindow = new BrowserWindow({
      height: 600,
      width: 800,
      title: appTitleLoading,
      icon: appIcon,
      webPreferences: {
        preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      }
    });
    mainWindow.setProgressBar(0.3);
    
    startApiService().then((res: boolean) => {
      simpleLogger.logDetail('api service res:', res);
      if(res) {
        createWebContentsView();
        setWebContentsDimensions();
        mainWindow.on('resize', () => {
          setWebContentsDimensions();
        });
        mainWindow.setProgressBar(.5);
        waitForUrl(settings.AppUrl, 1000, 10).then((res) => {
          simpleLogger.log(`Setting web contents url to: ${settings.AppUrl}`);
          webContentsView.webContents.loadURL(value.AppUrl); 
          mainWindow.setProgressBar(1);
          mainWindow.contentView.addChildView(webContentsView);
          mainWindow.title = appTitle;
          mainWindow.setProgressBar(-1);
        }).catch((err) => {
          simpleLogger.error(`Error waiting for App URL: ${err}`);
        });
      }
      else {
        simpleLogger.log('Service not started. Cannot display web app.');
      }
    })
  })
  // and load the index.html of the app.  Commented out as not required if using WebContentsView in full screen.
  //mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);  
};

function setWebContentsDimensions() {
  const { width, height } = mainWindow.getBounds();
  webContentsView.setBounds({ x: 0, y: 0, width: width, height: height });
}

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on('ready', createWindow);

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on('window-all-closed', () => {
  if(settings) {
    settings = null;
  }

  if(webContentsView) {
    webContentsView = null;
  }

  if(dotNetProcess) {
    dotNetProcess.kill();
    dotNetProcess = null;
  }

  if (process.platform !== 'darwin') {
    app.quit();
  }
});

app.on('activate', () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});

ipcMain.handle('read-settings', async () : Promise<ISettingsDefinition | null> => {
  return readSettings();
});

ipcMain.handle('select-file', async (event, opts: IFileDialogOptions) => {
  const result = await dialog.showOpenDialog({ properties: ['openFile'], filters: opts?.filters || [] });
  if (result.canceled || !result.filePaths || result.filePaths.length === 0) return null;
  return result.filePaths;
});

ipcMain.handle('save-settings', async (event, settings: ISettingsDefinition) => {
  try {
    const outPath = path.join(process.cwd(), 'settings.json');
    await fs.promises.writeFile(outPath, typeof settings === 'string' ? settings : JSON.stringify(settings, null, 2), 'utf8');
    return { ok: true, path: outPath } as ISaveSettingsResult;
  } catch (err) {
    return { ok: false, error: String(err) } as ISaveSettingsResult;
  }
});

