import { app, BrowserWindow, ipcMain, dialog, Menu, MenuItem, WebContentsView  } from 'electron';
import squirrelStartup from 'electron-squirrel-startup';

import { IFileDialogOptions } from './types/IFileDialogOptions.js';
import { ISettingsDefinition } from './types/ISettingsDefinition.js';
import { IWebAppServiceStatus } from './types/IWebAppServiceStatus.js';
import settingsService from './services/settingsService';
import webAppService from './services/webAppService';
import simpleLogger from './utils/simpleLogger';
import waitForUrl from './utils/waitForUrl';

// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code (depending on
// whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;
declare const SETTINGS_WINDOW_WEBPACK_ENTRY: string;
declare const SETTINGS_WINDOW_PRELOAD_WEBPACK_ENTRY: string;

let mainWindow: BrowserWindow | null = null;
let settingsWindow: BrowserWindow | null = null;

// Handle creating/removing shortcuts on Windows when installing/uninstalling.
if (squirrelStartup) {
  app.quit();
}

const menu = new Menu();
const submenu = Menu.buildFromTemplate([
  {
    label: 'Reload',
    accelerator: 'F5',
    click: () => {
      if(webContentsView && webContentsView.webContents) {
        simpleLogger.log('Reloading WebContentsView');
        webContentsView.webContents.reload();
      }
    }
  },
  {
    label: 'Settings',
    accelerator: 'F12',
    click: () => {
      openSettings();
    }
  },
  {
    label: 'Developer Tools',
    accelerator: 'CmdOrCtrl+Shift+I',
    click: () => {
      if(webContentsView) {
        // if there is a webContentsView loaded then use it's dev tools
        webContentsView.webContents.openDevTools({mode: 'detach'});
      } else {
        // follow this path when using the default index.html
        const windows = BrowserWindow.getAllWindows();
        windows.forEach(window =>  { 
          window.webContents.openDevTools({ mode: 'detach' });
        });
      }
    }
  }
]);
menu.append(new MenuItem({ label: 'File', submenu }));
Menu.setApplicationMenu(menu);

const openSettings = async () => {
  if(!mainWindow) {
    simpleLogger.error('Cannot show settings window if main window does not exist');
    return;
  }
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    settingsWindow.show();
    settingsWindow.focus();
    return;
  }
  settingsWindow = new BrowserWindow({
    width: 800,
    height: 520,
    parent: mainWindow || null,
    modal: false,
    frame: false,
    webPreferences: {
      sandbox: false, 
      contextIsolation: true,
      nodeIntegration: false,
      webviewTag: true,
      preload: SETTINGS_WINDOW_PRELOAD_WEBPACK_ENTRY,
    }
  });
  settingsWindow.removeMenu();
  settingsWindow.loadURL(SETTINGS_WINDOW_WEBPACK_ENTRY);
  settingsWindow.once('ready-to-show', () => {
    if(!settingsWindow) {
      simpleLogger.error('Settings Window does not exist.  Cannot show.');
      return;
    }
    settingsWindow.show();
  });
  settingsWindow.on('closed', () => { 
    simpleLogger.log('settings closed');
    settingsWindow = null; 
  });
};

const closeSettings = () => {
  if(settingsWindow && settingsWindow.closable) {
    simpleLogger.log('closing settings');
    settingsWindow.hide();  // use hide instead of close - because close is closing the parent window as well for some reason.
  }
}

let webContentsView: WebContentsView | null = null;
const createWebContentsView = (): void => {
  if(!webContentsView) {
    webContentsView = new WebContentsView();    
  }
}

const createWindow = (): void => {
  settingsService.readSettings().then((value: ISettingsDefinition | null) => {
    if(!value) {
      simpleLogger.log('No settings provided.  Using default settings.');
    }
    const settings = {...value} as ISettingsDefinition;
    settings.AppDisplayName = settings?.AppDisplayName ?? "Web Application Browser";
    settings.AppIcon = settings?.AppIcon ?? "";
    const appTitleLoading = `${settings.AppDisplayName} - Loading...`
    // Create the browser window.
    mainWindow = new BrowserWindow({
      height: 600,
      width: 800,
      title: appTitleLoading,
      icon: settings.AppIcon,
      autoHideMenuBar: true,
      webPreferences: {
        preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
        devTools: true
      }
    });
    mainWindow.setProgressBar(0.3);
    
    webAppService.startWebApp().then((webAppServiceStatus: IWebAppServiceStatus) => {
      simpleLogger.logDetail('Start Web App result:', webAppServiceStatus); 
      if(!mainWindow) {
        simpleLogger.error('MainWindow is undefined');
        return;
      }
      if(webAppServiceStatus && webAppServiceStatus.isRunning) {
        createWebContentsView();
        setWebContentsDimensions();
        mainWindow.on('resize', () => {
          setWebContentsDimensions();
        });
        mainWindow.setProgressBar(.5);
        waitForUrl(settings.AppUrl, 1000, 10).then(() => {
          simpleLogger.log(`Setting web contents url to: ${settings.AppUrl}`);
          if(!webContentsView) {
            simpleLogger.error('WebContentsView is undefined');
            return;
          }
          if(!mainWindow) {
            simpleLogger.error('MainWindow is undefined');
            return;
          }
          webContentsView.webContents.loadURL(settings.AppUrl); 
          mainWindow.setProgressBar(1);
          mainWindow.contentView.addChildView(webContentsView);
          mainWindow.title = settings.AppDisplayName;
          mainWindow.setProgressBar(-1);
        }).catch((err) => {
          simpleLogger.error(`Error waiting for App URL: ${err}`);
        });
      }
      else {
        simpleLogger.error('Web App not started. Cannot browse to app url.');
        if(webAppServiceStatus.error) {
          simpleLogger.error(`WebAppService error: ${webAppServiceStatus.error}`);
        }
        mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY); // revert to basic html content
      }
    })
  })
};

function setWebContentsDimensions() {
  if(mainWindow && webContentsView) {
    const { width, height } = mainWindow.getBounds();
    webContentsView.setBounds({ x: 0, y: 0, width: width, height: height });
  } else {
    simpleLogger.log('Dimensions not set. MainWindow or WebContentsView not defined.');
  }
}

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on('ready', createWindow);

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on('window-all-closed', () => {
  settingsService.clearSettings();

  if(webContentsView) {
    webContentsView = null;
  }

  webAppService.clearWebAppProcess();

  if (process.platform !== 'darwin') {
    app.quit();
  }
});

app.on('activate', () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});

ipcMain.handle('read-settings', async () : Promise<ISettingsDefinition | null> => {
  return settingsService.readSettings();
});

ipcMain.handle('select-file', async (event, opts: IFileDialogOptions) => {
  const result = await dialog.showOpenDialog({ properties: ['openFile'], filters: opts?.filters || [] });
  if (result.canceled || !result.filePaths || result.filePaths.length === 0) return null;
  return result.filePaths;
});

ipcMain.handle('save-settings', async (event, settings: ISettingsDefinition) => {
  return settingsService.saveSettings(settings);
});

ipcMain.handle('log', (event, message: string) => {
  simpleLogger.log(message);
});

// eslint-disable-next-line @typescript-eslint/no-explicit-any
ipcMain.handle('log-detail', (event, message: string, obj: any) => {
  simpleLogger.logDetail(message, obj);
});

ipcMain.handle('log-error', (event, message: string) => {
  simpleLogger.error(message);
});

// eslint-disable-next-line @typescript-eslint/no-explicit-any
ipcMain.handle('log-error-detail', (event, message: string, err: any) => {
  simpleLogger.errorDetail(message, err);
});

ipcMain.handle('open-settings-window', () => {
  openSettings();
});

ipcMain.handle('close-settings-window', () => {
  closeSettings();
});
